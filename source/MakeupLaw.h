// Same table for every detector variant (they compress music by the same amount).
inline double lookup (double compression, int mode)
{
    const double* t = mode == 0 ? compress : limit;
    const double x = compression < 0.0 ? 0.0 : (compression > 100.0 ? 100.0 : compression);
    const int i = x >= 100.0 ? 99 : (int) x;
    const double f = x - i;
    return t[i] + f * (t[i + 1] - t[i]);
}
